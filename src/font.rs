#[derive(Debug, Clone, Copy)]
pub struct GlyphCacheEntry {
    pub character: char,
    pub bitmap: [u8; 8],
}

pub struct FontManager {
    pub glyph_cache: [Option<GlyphCacheEntry>; 64],
}

impl FontManager {
    pub const fn new() -> Self {
        Self {
            glyph_cache: [None; 64],
        }
    }

    pub fn get_glyph(&mut self, c: char) -> [u8; 8] {
        let cache_idx = (c as usize) % 64;
        if let Some(entry) = self.glyph_cache[cache_idx] {
            if entry.character == c {
                return entry.bitmap;
            }
        }

        let bmp = lookup_glyph_bitmap(c);
        self.glyph_cache[cache_idx] = Some(GlyphCacheEntry { character: c, bitmap: bmp });
        bmp
    }
}

pub static FONT_MANAGER: Mutex<FontManager> = Mutex::new(FontManager::new());

/// Looks up the 8x8 bitmap for ASCII and Turkish UTF-8 characters
pub fn lookup_glyph_bitmap(c: char) -> [u8; 8] {
    match c {
        'ç' => GLYPH_TURKISH_C_LOWER,
        'Ç' => GLYPH_TURKISH_C_UPPER,
        'ğ' => GLYPH_TURKISH_G_LOWER,
        'Ğ' => GLYPH_TURKISH_G_UPPER,
        'ı' => GLYPH_TURKISH_I_DOTLESS,
        'İ' => GLYPH_TURKISH_I_DOTTED,
        'ö' => GLYPH_TURKISH_O_LOWER,
        'Ö' => GLYPH_TURKISH_O_UPPER,
        'ş' => GLYPH_TURKISH_S_LOWER,
        'Ş' => GLYPH_TURKISH_S_UPPER,
        'ü' => GLYPH_TURKISH_U_LOWER,
        'Ü' => GLYPH_TURKISH_U_UPPER,
        _ => {
            let ascii = (c as u32).min(127) as usize;
            FONT[ascii]
        }
    }
}

/// Measures the pixel width and height of a UTF-8 text string
pub fn measure_text(text: &str) -> (u32, u32) {
    let mut max_width = 0u32;
    let mut cur_width = 0u32;
    let mut lines = 1u32;

    for c in text.chars() {
        if c == '\n' {
            lines += 1;
            if cur_width > max_width { max_width = cur_width; }
            cur_width = 0;
        } else {
            cur_width += 8;
        }
    }
    if cur_width > max_width { max_width = cur_width; }
    (max_width, lines * 10)
}

/// Draws a single glyph into a surface buffer with boundary clipping
pub fn draw_glyph(surface: *mut u32, surf_w: u32, surf_h: u32, x: u32, y: u32, c: char, fg: u32, bg: u32) {
    if surface.is_null() || x >= surf_w || y >= surf_h {
        return;
    }

    let bitmap = lookup_glyph_bitmap(c);

    for row in 0..8u32 {
        let py = y + row;
        if py >= surf_h { break; }
        let byte = bitmap[row as usize];

        for col in 0..8u32 {
            let px = x + col;
            if px >= surf_w { break; }

            let color = if (byte & (1 << (7 - col))) != 0 { fg } else { bg };
            let offset = (py as usize) * (surf_w as usize) + (px as usize);
            unsafe {
                core::ptr::write_volatile(surface.add(offset), color);
            }
        }
    }
}

/// Draws a UTF-8 string into a surface buffer with newline handling and clipping
pub fn draw_text(surface: *mut u32, surf_w: u32, surf_h: u32, start_x: u32, start_y: u32, text: &str, fg: u32, bg: u32) {
    if surface.is_null() { return; }

    let mut cx = start_x;
    let mut cy = start_y;

    for c in text.chars() {
        if c == '\n' {
            cx = start_x;
            cy += 10;
            if cy + 8 > surf_h {
                break;
            }
            continue;
        }

        if cx + 8 <= surf_w && cy + 8 <= surf_h {
            draw_glyph(surface, surf_w, surf_h, cx, cy, c, fg, bg);
        }
        cx += 8;
    }
}

/// Draws centered text inside a bounding rectangle
pub fn draw_centered_text(surface: *mut u32, surf_w: u32, surf_h: u32, rx: i32, ry: i32, rw: u32, rh: u32, text: &str, fg: u32, bg: u32) {
    let (tw, th) = measure_text(text);
    let cx = rx + (rw as i32 - tw as i32) / 2;
    let cy = ry + (rh as i32 - th as i32) / 2;
    if cx >= 0 && cy >= 0 {
        draw_text(surface, surf_w, surf_h, cx as u32, cy as u32, text, fg, bg);
    }
}
